import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {chromium} from 'playwright';
const php=process.env.PHP_BINARY||'php';
const screenshotRoot=resolve(process.env.ORTHOCAL_TEST_ARTIFACTS||'artifacts');
mkdirSync(screenshotRoot,{recursive:true});
const html=(lang='de',mode='day',office='horologion',textLanguage='',work='')=>execFileSync(php,['-n','scripts/wordpress-reader-fixture.php',lang,mode,office,textLanguage,work],{encoding:'utf8'});
const german=html();
const hour=html('ru','horologion','sixth-hour');
assert.match(hour,/Боже, именем Твоим спаси меня/);
assert.doesNotMatch(hour.replace(/<[^>]+>/g,""),/Textzuordnung|Справочный текст|требуют уточнения/);
assert.match(german,/9\. September 2026/);assert.match(german,/15\. Woche nach Pfingsten/);assert.match(german,/Ton 6/);
assert.match(german,/Text kopieren/);assert.match(german,/Troparien/);assert.match(german,/Kalenderwerkstatt/);
const browser=await chromium.launch(process.platform==='win32'?{channel:'msedge'}:{});
try{
 const page=await browser.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('https://reader.test/**',async route=>{
   const url=new URL(route.request().url());
   if(url.pathname==='/api/render')return route.fulfill({json:{html:html(url.searchParams.get('lang'),url.searchParams.get('mode'),url.searchParams.get('office'),url.searchParams.get('text_language')||'',url.searchParams.get('work')||'')}});
   if(url.pathname==='/api/bible')return route.fulfill({json:[]});
   return route.fulfill({contentType:'text/html',body:'<!doctype html><meta charset="utf-8">'+german});
 });
 await page.goto('https://reader.test/');
 await page.addStyleTag({content:readFileSync('wordpress/orthocal/assets/calendar.css','utf8')});
 await page.addScriptTag({path:resolve('wordpress/orthocal/assets/calendar.js')});
 assert.equal(await page.locator('[data-oc-copy-reading]').textContent(),'Text kopieren');
 assert.equal(await page.locator('[data-oc-library="troparia"]').innerText(),'Troparien');
 assert.match(await page.locator('.oc-profile-note').innerText(),/Klosterprofil/);
 assert.match(await page.locator('.oc-reading-translation').innerText(),/Übersetzung/);
 assert.doesNotMatch(await page.locator('.orthocal').innerText(),/[А-Яа-яЁё]/);
 await page.locator('[data-oc-library="horologion"]').click();
 await page.locator('[data-oc-library-language]').waitFor();
 assert.equal(await page.locator('dialog .oc-library-content').count(),0,'German must not display a Slavonic fallback');
 await page.locator('[data-oc-library-language]').selectOption('ru');
 await page.locator('dialog .oc-library-content').waitFor();
 const russian=await page.locator('dialog .oc-library-content').innerText();
 assert.ok(russian.length>1000);
 assert.match(russian,/Боже, именем Твоим спаси меня/);
 await page.locator('[data-oc-library-language]').selectOption('cu-civil');
 await page.waitForFunction(()=>document.querySelector('.oc-library-content')?.textContent.includes('Боже, во имя'));
 assert.notEqual(await page.locator('dialog .oc-library-content').innerText(),russian);
 assert.doesNotMatch(await page.locator('dialog .oc-library-content').evaluate(el=>getComputedStyle(el).fontFamily),/Monomakh/);
 assert.equal(await page.locator('dialog').count(),1);
 await page.locator('[data-oc-library-work]').selectOption('chas-pervyj');
 await page.locator('dialog h3',{hasText:'Час первый'}).waitFor();
 await page.locator('[data-oc-library-language]').selectOption('pl');
 await page.waitForFunction(()=>!document.querySelector('dialog .oc-library-content'));
 await page.locator('[data-oc-library-language]').selectOption('ru');
 await page.locator('dialog .oc-library-content').waitFor();
 await page.screenshot({path:resolve(screenshotRoot,'wordpress-reader-de.png')});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.locator('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,'Mobile reader must not overflow horizontally');
 await page.locator('.oc-dialog-close').click();assert.equal(await page.locator('dialog[open]').count(),0);
 await page.locator('[data-oc-library="horologion"]').click();await page.locator('[data-oc-library-language]').waitFor();
 await page.keyboard.press('Escape');assert.equal(await page.locator('dialog[open]').count(),0);
 assert.deepEqual(errors,[]);
 console.log('PASS German server HTML, full prayer bodies, language/office updates in one dialog, one-click close, Escape, reopen');
}finally{await browser.close();}
