import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {createServer} from 'node:net';
import {mkdirSync,readFileSync} from 'node:fs';
import {chromium} from 'playwright';
import {readWordPressPluginVersion} from './wordpress-plugin-version.mjs';
const wordpressPluginDownload=`/downloads/orthocal-${readWordPressPluginVersion()}.zip`;
const translatorPluginDownload='/downloads/georg-kloster-slavonic-translator-1.0.5.zip';
const probe=createServer();await new Promise(r=>probe.listen(0,'127.0.0.1',r));const port=probe.address().port;await new Promise(r=>probe.close(r));
const origin=`http://127.0.0.1:${port}`;
const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port',String(port),'--strictPort'],{windowsHide:true,stdio:'ignore'});
let browser;
try {
  for(let i=0;i<60;i++){try{if((await fetch(origin)).ok)break;}catch{}await new Promise(r=>setTimeout(r,100));}
  browser=await chromium.launch(process.platform==='win32'?{channel:'msedge'}:{});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[],requests=[];
  page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>requests.push(r.url()));
  await page.route('**/api/**',route=>route.fulfill({contentType:'application/json',body:JSON.stringify(route.request().url().includes('calendar-access/plans')?{plans:[{id:'free',name:'Free',priceCents:0,currency:'EUR',perMinute:30,perDay:300,perMonth:1000}],settings:{contactEmail:'test@example.invalid'}}:{items:[],pages:[]})}));
  await page.goto(origin);await page.getByRole('link',{name:'API календаря',exact:true}).click();
  await page.getByRole('heading',{name:'API календаря',exact:true}).waitFor();
  await page.getByRole('heading',{name:'Free',exact:true}).waitFor();
  assert.ok(page.url().endsWith('/calendar-api'));
  assert.equal(await page.getByRole('link',{name:'Запросить API-ключ'}).getAttribute('href'),'mailto:test@example.invalid');
  const catalog=page.locator('#plugins');
  assert.equal(await catalog.locator('tbody tr').count(),3);
  assert.equal(await catalog.locator('a.download').nth(0).getAttribute('href'),wordpressPluginDownload);
  assert.equal(await catalog.locator('a.download').nth(1).getAttribute('href'),'/downloads/kloster-prayer-1.2.5.zip');
  assert.equal(await catalog.locator('tbody tr').nth(1).locator('.version').textContent(),'1.2.5');
  assert.equal(await catalog.locator('a.download').nth(2).getAttribute('href'),translatorPluginDownload);
  const translatorRow=catalog.locator('tbody tr').nth(2);
  assert.ok((await translatorRow.textContent()).includes('Georg-Kloster Slavonic Translator'));
  assert.equal(await translatorRow.locator('.version').textContent(),'1.0.5');
  const translatorZip=await fetch(origin+translatorPluginDownload);
  assert.equal(translatorZip.status,200);
  const translatorBytes=Buffer.from(await translatorZip.arrayBuffer());
  assert.equal(translatorBytes.subarray(0,2).toString(),'PK');
  assert.deepEqual(translatorBytes,readFileSync('artifacts/georg-kloster-slavonic-translator-1.0.5.zip'));
  assert.equal(await page.locator('details[open]').count(),0);
  mkdirSync('tmp/plugin-catalog',{recursive:true});
  await catalog.screenshot({path:'tmp/plugin-catalog/desktop.png'});
  await catalog.getByRole('link',{name:'Подробнее о календаре',exact:true}).click();
  assert.equal(await page.locator('#wordpress').getAttribute('open'),'');
  const pluginLink=page.locator('#wordpress a.download');
  assert.equal(await pluginLink.getAttribute('href'),wordpressPluginDownload);
  assert.match(await page.locator('#wordpress').textContent(),/работает сразу, без регистрации и API-ключа/);
  const prayerSection=page.locator('#prayer-plugin');
  await catalog.getByRole('link',{name:'Подробнее о молитвенных записках',exact:true}).click();
  assert.equal(await prayerSection.getAttribute('open'),'');
  assert.equal(await prayerSection.locator('a.download').getAttribute('href'),'/downloads/kloster-prayer-1.2.5.zip');
  const prayerZip=await fetch(origin+'/downloads/kloster-prayer-1.2.5.zip');
  assert.equal(prayerZip.status,200);
  const prayerBytes=Buffer.from(await prayerZip.arrayBuffer());
  assert.equal(prayerBytes.subarray(0,2).toString(),'PK');
  assert.deepEqual(prayerBytes,readFileSync('artifacts/kloster-prayer-1.2.5.zip'));
  assert.match(await prayerSection.textContent(),/email получателя уведомлений/);
  const translatorSection=page.locator('#translator-plugin');
  await catalog.getByRole('link',{name:'Подробнее о переводчике',exact:true}).click();
  await translatorSection.getByRole('heading',{name:'Церковнославянский переводчик для WordPress'}).waitFor();
  assert.equal(await translatorSection.locator('a.download').getAttribute('href'),translatorPluginDownload);
  assert.equal(await translatorSection.locator('a').filter({hasText:/Исходный код/i}).count(),0);
  assert.match(await translatorSection.textContent(),/Бесплатный режим работает сразу/);
  assert.match(await translatorSection.textContent(),/Georg-Kloster Slavonic Translator/);
  assert.match(await translatorSection.textContent(),/деактивируйте старую копию/);
  assert.match(await page.locator('#connection').textContent(),/X-Calendar-Client: orthocal-wordpress/);
  const guide=await fetch(origin+'/downloads/calendar-api-guide.md');assert.equal(guide.status,200);const guideText=await guide.text();assert.ok(guideText.includes('X-API-Key'));assert.ok(guideText.includes(wordpressPluginDownload));
  assert.ok(!requests.some(url=>/\/assets\/(?:App-|pdf-exporter-)/.test(url)),'Editor must not load on home/docs');
  if(process.env.CALENDAR_API_DOCS_SCREENSHOTS!=='0'){mkdirSync('artifacts',{recursive:true});await page.screenshot({path:'artifacts/calendar-api-docs-desktop.png',fullPage:true});}
  await page.setViewportSize({width:390,height:844});assert.ok(await page.evaluate(()=>document.querySelector('.route-shell').scrollWidth<=innerWidth));if(process.env.CALENDAR_API_DOCS_SCREENSHOTS!=='0')await page.screenshot({path:'artifacts/calendar-api-docs-mobile.png',fullPage:true});
  await catalog.screenshot({path:'tmp/plugin-catalog/mobile.png'});
  await page.reload();await page.getByRole('heading',{name:'API календаря',exact:true}).waitFor();
  assert.equal(await page.locator('#translator-plugin').getAttribute('open'),'');
  assert.deepEqual(errors,[]);console.log('PASS home link, documentation route/reload, published plans/contact, real ZIP and guide, mobile width, no editor download');
}finally{await browser?.close();server.kill();}
